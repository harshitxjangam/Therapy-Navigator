def load_sample():
    """Fill the form with a realistic week. Runs before the widgets exist."""
    for field, value in SAMPLE.items():
        st.session_state[field] = value


for key, value in DEFAULTS.items():
    if key not in st.session_state:
        st.session_state[key] = value

if "ops_report" not in st.session_state:
    st.session_state.ops_report = None
if "ops_payload" not in st.session_state:
    st.session_state.ops_payload = None

# --------------------------------------------------------------------------- #
# Header
# --------------------------------------------------------------------------- #
page_header(
    "📊 Operations Report Generator",
    "Turn raw numbers into a leadership-ready summary",
)

how_it_works(
    "Enter the week's raw clinic numbers. The AI calculates the derived "
    "metrics leadership actually asks about — completion rate, cancellation "
    "rate, therapist utilization, authorization approval and denial rates — "
    "flags anything outside a normal range, folds in your written notes, and "
    "closes with concrete recommended actions. Output is a formatted document "
    "you can download and forward."
)
api_key_banner()


def build_payload():
    """Assemble the data block sent to the model."""
    completed = st.session_state.ops_completed
    canceled = st.session_state.ops_canceled
    scheduled = completed + canceled

    lines = [
        "Clinic name: {}".format(st.session_state.ops_clinic or "Our Clinic"),
        "Report period: {}".format(st.session_state.ops_period or "This period"),
        "",
        "Total appointments completed: {}".format(completed),
        "Appointments canceled or no-show: {}".format(canceled),
        "Total appointments scheduled (completed + canceled): {}".format(scheduled),
        "New patient evaluations: {}".format(st.session_state.ops_evals),
        "New referrals received: {}".format(st.session_state.ops_referrals),
        "Current waitlist size: {}".format(st.session_state.ops_waitlist),
        "Insurance authorizations approved: {}".format(
            st.session_state.ops_auth_approved
        ),
        "Insurance authorizations pending: {}".format(
            st.session_state.ops_auth_pending
        ),
        "Insurance authorizations denied: {}".format(
            st.session_state.ops_auth_denied
        ),
        "Active therapists this period: {}".format(st.session_state.ops_therapists),
        "Available therapy hours used: {}%".format(st.session_state.ops_utilization),
    ]

    if st.session_state.ops_compare:
        lines += [
            "",
            "PRIOR PERIOD COMPARISON:",
            "Previous appointments completed: {}".format(
                st.session_state.ops_prev_completed
            ),
            "Previous waitlist size: {}".format(st.session_state.ops_prev_waitlist),
            "Previous new referrals: {}".format(st.session_state.ops_prev_referrals),
        ]

    notes = st.session_state.ops_notes.strip()
    lines += [
        "",
        "Notes, highlights or concerns from the team:",
        notes if notes else "None provided.",
        "",
        "Today's date: {}".format(date.today().strftime("%B %d, %Y")),
    ]
    return "\n".join(lines)


def generate(reframe=False):
    payload = build_payload()
    system = SYSTEM_PROMPT + (REFRAME_NOTE if reframe else "")
    return payload, call_claude(system, payload, max_tokens=2500)


