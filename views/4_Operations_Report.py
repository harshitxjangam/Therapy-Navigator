# Output
# --------------------------------------------------------------------------- #
if submitted:
    if st.session_state.ops_completed == 0 and st.session_state.ops_canceled == 0:
        st.session_state.ops_report = None
        with right:
            st.error(
                "Enter at least the completed and canceled appointment counts "
                "— the report is built from those numbers."
            )
    else:
        with right:
            with st.spinner("Generating your operations report..."):
                payload, report = generate()
        if is_error(report):
            st.session_state.ops_report = None
            with right:
                st.error(error_body(report))
                st.caption("Try again — most issues clear up on a second attempt.")
        else:
            st.session_state.ops_report = report
            st.session_state.ops_payload = payload

with right:
    report = st.session_state.ops_report

    if report is None and not submitted:
        st.subheader("Your report")
        st.info(
            "Enter this period's numbers on the left and select **Generate "
            "report** — the formatted summary appears here."
        )

        completed = st.session_state.ops_completed
        canceled = st.session_state.ops_canceled
        if completed or canceled:
            scheduled = completed + canceled
            metric_cols = st.columns(2)
            metric_cols[0].metric("Scheduled", scheduled)
            metric_cols[1].metric(
                "Cancel / no-show rate",
                "{:.1f}%".format(100 * canceled / scheduled) if scheduled else "—",
            )

    elif report:
        st.subheader("Your report")
        with st.container(border=True):
            st.markdown(
                '<span class="report-doc-marker"></span>', unsafe_allow_html=True
            )
            st.markdown(report)

        st.write("")
        action_a, action_b = st.columns(2)
        with action_a:
            st.download_button(
                "Download report (.txt)",
                data=report,
                file_name="operations_report_{}.txt".format(
                    date.today().isoformat()
                ),
                mime="text/plain",
                use_container_width=True,
            )
        with action_b:
            regenerate = st.button(
                "Regenerate with a new angle", use_container_width=True
            )

        with st.expander("Copy report text"):
            st.caption(
                "Hover the box and use the copy icon in its top-right corner."
            )
            st.code(report, language=None)

        with st.expander("Data sent to the model"):
            st.text(st.session_state.ops_payload or "")

        if regenerate:
            with st.spinner("Generating your operations report..."):
                payload, new_report = generate(reframe=True)
            if is_error(new_report):
                st.error(error_body(new_report))
            else:
                st.session_state.ops_report = new_report
                st.session_state.ops_payload = payload
                st.rerun()

